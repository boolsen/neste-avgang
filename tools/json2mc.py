"""Convert JSON fixture files into a Monkey C module of fixture functions.

Usage: python3 -I tools/json2mc.py test/fixtures/json/*.json > test/Fixtures.mc
Each file <stem>.json becomes `function <stem>() as Dictionary`.
"""
import json
import pathlib
import sys


def lit(v, indent):
    pad = "    " * indent
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, int):
        return f"{v}l" if abs(v) > 2**31 - 1 else str(v)
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    if isinstance(v, list):
        if not v:
            return "[]"
        inner = (",\n").join(pad + "    " + lit(x, indent + 1) for x in v)
        return "[\n" + inner + "\n" + pad + "]"
    if isinstance(v, dict):
        if not v:
            return "{}"
        inner = (",\n").join(pad + "    " + lit(k, 0) + " => " + lit(x, indent + 1) for k, x in v.items())
        return "{\n" + inner + "\n" + pad + "}"
    raise TypeError(type(v))


out = ["// GENERATED by tools/json2mc.py - do not edit", "import Toybox.Lang;", "", "module Fixtures {"]
for path in sorted(sys.argv[1:]):
    p = pathlib.Path(path)
    data = json.loads(p.read_text(encoding="utf-8"))
    out.append(f"    function {p.stem}() as Dictionary {{")
    out.append("        return " + lit(data, 2) + ";")
    out.append("    }")
    out.append("")
out.append("}")
sys.stdout.write("\n".join(out) + "\n")
